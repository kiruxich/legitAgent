import { DISCLAIMER_RU } from './disclaimer.js';

export interface PolicyInput {
  operator: string;
  inn?: string;
  ogrn?: string;
  email?: string;
  site?: string;
  address?: string;
}

export function generatePolicyMarkdown(input: PolicyInput): string {
  const operator = input.operator.trim();
  if (!operator) throw new Error('Укажите наименование оператора');
  const inn = input.inn?.trim() || '[ИНН]';
  const ogrn = input.ogrn?.trim() || '[ОГРН]';
  const email = input.email?.trim() || '[email]';
  const site = input.site?.trim() || '[сайт]';
  const address = input.address?.trim() || '[адрес в РФ]';
  return `# Политика обработки персональных данных

${DISCLAIMER_RU} Документ — черновик для юриста, не готовая политика.

## 1. Оператор

Оператор: **${operator}**, ИНН ${inn}, ОГРН ${ogrn}, адрес ${address}.
Сайт: ${site}. Запросы субъектов: ${email}.

## 2. Цели и правовые основания

Оператор обрабатывает персональные данные, чтобы:

- ответить на обращение через форму на сайте;
- заключить и исполнить договор, если пользователь его заключает;
- направить служебные сообщения по работе сайта.

Правовые основания: согласие субъекта (ст. 9 152-ФЗ); договор, стороной которого является субъект; законные интересы оператора в пределах 152-ФЗ.

## 3. Состав данных

Имя, адрес электронной почты, номер телефона, иные сведения, которые субъект сам направил через формы сайта, технические данные (IP, cookie) — если они собираются.

## 4. Сроки

Данные хранятся до отзыва согласия, либо в течение срока, нужного для цели обработки, либо в сроки, установленные законом (бухгалтерия, претензии).

## 5. Отзыв согласия и права субъекта

Субъект вправе отозвать согласие, запросить доступ, уточнение или удаление, направив заявление на ${email}. Оператор отвечает в сроки ст. 20 152-ФЗ.

## 6. Локализация

Запись, систематизация, накопление и хранение персональных данных граждан РФ осуществляются с использованием баз данных, находящихся на территории Российской Федерации (ст. 18 152-ФЗ).

## 7. Передача третьим лицам

Передача допускается обработчикам по поручению оператора и в случаях, предусмотренных законом. Трансграничная передача — только при наличии оснований, предусмотренных 152-ФЗ.

## 8. Cookie

Необязательные аналитические cookie ставятся после согласия. Отказ от необязательных cookie доступен в баннере.

## 9. Уведомление Роскомнадзора

Оператор уведомляет уполномоченный орган о намерении обрабатывать персональные данные, если закон не освобождает от уведомления (ст. 22 152-ФЗ).

## 10. Изменения

Актуальная редакция публикуется на ${site}.
`;
}
